#!/usr/bin/env python3
"""Build a small read-only FAT12 image from a folder and emit it as C.

Usage: mkdisk.py <source_dir> <output.c>

Every file in source_dir must have a lowercase 8.3 name (e.g. install.sh).
The image is served by the firmware's USB drive in config mode.
"""
import os
import re
import struct
import sys

SECTOR = 512
ROOT_ENTRIES = 64
LABEL = b"PPBOX      "
NAME_RE = re.compile(r"^[a-z0-9_-]{1,8}(\.[a-z0-9_-]{1,3})?$")


def short_name(fn):
    if not NAME_RE.match(fn):
        sys.exit(f"mkdisk: '{fn}' is not a lowercase 8.3 name")
    base, _, ext = fn.partition(".")
    return base.upper().ljust(8).encode() + ext.upper().ljust(3).encode()


def build(src):
    files = []
    for fn in sorted(os.listdir(src)):
        p = os.path.join(src, fn)
        if os.path.isfile(p) and not fn.startswith("."):
            with open(p, "rb") as f:
                files.append((fn, f.read()))
    if len(files) > ROOT_ENTRIES - 1:
        sys.exit("mkdisk: too many files")

    clusters_needed = sum(max(1, -(-len(d) // SECTOR)) for _, d in files)
    n_clusters = max(64, clusters_needed + 16)
    fat_bytes = (n_clusters + 2) * 3 // 2 + 1
    fat_sectors = -(-fat_bytes // SECTOR)
    root_sectors = ROOT_ENTRIES * 32 // SECTOR
    reserved = 1
    data_start = reserved + 2 * fat_sectors + root_sectors
    total = data_start + n_clusters

    img = bytearray(total * SECTOR)

    # Boot sector / BPB
    bs = bytearray(SECTOR)
    bs[0:3] = b"\xEB\x3C\x90"
    bs[3:11] = b"MSWIN4.1"
    struct.pack_into("<HBHBHHBHHHII", bs, 11,
                     SECTOR, 1, reserved, 2, ROOT_ENTRIES,
                     total if total < 65536 else 0, 0xF8, fat_sectors,
                     1, 1, 0, total if total >= 65536 else 0)
    bs[36] = 0x80          # drive number
    bs[38] = 0x29          # extended boot signature
    struct.pack_into("<I", bs, 39, 0x50504258)  # volume serial
    bs[43:54] = LABEL
    bs[54:62] = b"FAT12   "
    bs[510:512] = b"\x55\xAA"
    img[0:SECTOR] = bs

    # FAT
    fat = [0] * (n_clusters + 2)
    fat[0], fat[1] = 0xFF8, 0xFFF
    root = bytearray(root_sectors * SECTOR)

    # Volume label entry
    root[0:11] = LABEL
    root[11] = 0x08

    next_cluster = 2
    for i, (fn, data) in enumerate(files, start=1):
        n = max(1, -(-len(data) // SECTOR))
        first = next_cluster if data else 0
        for k in range(n):
            c = next_cluster + k
            fat[c] = c + 1 if k < n - 1 else 0xFFF
            off = (data_start + (c - 2)) * SECTOR
            chunk = data[k * SECTOR:(k + 1) * SECTOR]
            img[off:off + len(chunk)] = chunk
        next_cluster += n
        e = bytearray(32)
        e[0:11] = short_name(fn)
        e[11] = 0x01            # read-only
        base, _, ext = fn.partition(".")
        e[12] = 0x08 | (0x10 if ext else 0)  # display base/ext in lowercase
        struct.pack_into("<HH", e, 14, 0, 0x5948)  # time, date (2024-10-08)
        struct.pack_into("<H", e, 18, 0x5948)
        struct.pack_into("<HH", e, 22, 0, 0x5948)
        struct.pack_into("<HI", e, 26, first, len(data))
        root[i * 32:(i + 1) * 32] = e

    packed = bytearray(fat_sectors * SECTOR)
    for c in range(0, len(fat), 2):
        a = fat[c]
        b = fat[c + 1] if c + 1 < len(fat) else 0
        o = c * 3 // 2
        packed[o] = a & 0xFF
        packed[o + 1] = ((a >> 8) & 0x0F) | ((b & 0x0F) << 4)
        packed[o + 2] = (b >> 4) & 0xFF
    for k in range(2):
        off = (reserved + k * fat_sectors) * SECTOR
        img[off:off + len(packed)] = packed
    off = (reserved + 2 * fat_sectors) * SECTOR
    img[off:off + len(root)] = root
    return img, [fn for fn, _ in files]


def main():
    src, out = sys.argv[1], sys.argv[2]
    img, names = build(src)
    with open(out, "w") as f:
        f.write("// Generated by tools/mkdisk.py - do not edit.\n")
        f.write("// Files: " + ", ".join(names) + "\n#include <stdint.h>\n")
        f.write(f"const uint32_t disk_image_size = {len(img)};\n")
        f.write("const uint8_t disk_image[] = {\n")
        for i in range(0, len(img), 16):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in img[i:i + 16]) + ",\n")
        f.write("};\n")
    if len(sys.argv) > 3:  # optional raw image for testing
        with open(sys.argv[3], "wb") as f:
            f.write(img)


if __name__ == "__main__":
    main()
